export function buildSeedReviews(): Review[] {
  return HARDCODED_TESTIMONIALS.map((text, i) => ({
    id: `legacy-rev-${String(i + 1).padStart(3, '0')}`,
    textAr: text,
    textEn: '',
    authorLabelAr: `عميلة موثّقة #${String(i + 1).padStart(2, '0')}`,
    authorLabelEn: `Verified Client #${String(i + 1).padStart(2, '0')}`,
    rating: 5,
    active: true,
  }));
}

export async function seedHardcodedReviews(): Promise<void> {
  const reviews = buildSeedReviews();
  for (const rev of reviews) {
    const { id, ...rest } = rev;
    await setDoc(doc(db, COL, id), { ...rest, createdAt: serverTimestamp() });
  }
}
